/** دسته‌بندی گیاه */
enum class PlantCat(val title: String) {
    FOLIAGE("برگ‌زینتی"), FLOWER("گل‌دار"), SUCCULENT("کاکتوس و گوشتی"), PALM("نخل و درختچه"), HANGING("رونده و آویز"),
}

/** برچسب‌های کاربردی برای جستجو و مشاور خرید */
enum class Tag(val title: String) {
    BEGINNER("مناسب مبتدی"), LOW_LIGHT("کم‌نورپسند"), OFFICE("مناسب محل کار"), BEDROOM("مناسب اتاق خواب"),
    PET_SAFE("بی‌خطر برای حیوانات"), AIR("تصفیه‌کننده هوا"), FLOWER("گل‌دار"), HANGING("آویز و رونده"),
    GIFT("مناسب هدیه"), TRAVEL("مقاوم به بی‌آبی و سفر"), BIG("درختچه بزرگ"), SMALL("کوچک و رومیزی"),
}

/** سطوح نور: ۱ کم‌نور، ۲ نور متوسط غیرمستقیم، ۳ نور زیاد غیرمستقیم، ۴ آفتاب مستقیم */
object Light {
    val names = listOf("", "کم‌نور (دور از پنجره)", "نور متوسط غیرمستقیم", "نور زیاد غیرمستقیم", "آفتاب مستقیم")
    val short = listOf("", "کم‌نور", "متوسط", "روشن", "آفتابی")
    fun range(a: Int, b: Int) = if (a == b) names[a] else "${short[a]} تا ${short[b]}"
}

data class PlantInfo(
    val id: String,
    val fa: String,
    val sci: String,
    val aka: String,
    val family: String,
    val origin: String,
    val cat: PlantCat,
    /** سختی نگهداری ۱ آسان تا ۳ دشوار */
    val level: Int,
    val lightMin: Int,
    val lightMax: Int,
    /** فاصله تقریبی آبیاری (روز) در فصل گرم و سرد */
    val waterSummer: Int,
    val waterWinter: Int,
    val water: String,
    /** نیاز رطوبتی ۱ کم، ۲ متوسط، ۳ زیاد */
    val humidity: Int,
    val tempMin: Int,
    val tempMax: Int,
    val soil: String,
    val fert: String,
    val propagate: String,
    val petSafe: Boolean,
    val toxicity: String,
    val growth: String,
    /** اندازه ۱ کوچک، ۲ متوسط، ۳ بزرگ */
    val size: Int,
    val tags: Set<Tag>,
    val intro: String,
    val buy: List<String>,
    val tips: List<String>,
    val problems: List<String>,
) {
    val levelTitle get() = listOf("", "آسان", "متوسط", "حرفه‌ای")[level]
    val humidityTitle get() = listOf("", "کم (هوای معمولی خانه کافی است)", "متوسط", "زیاد (رطوبت‌ساز یا سینی سنگ‌ریزه)")[humidity]
    val sizeTitle get() = listOf("", "کوچک و رومیزی", "متوسط", "بزرگ و ایستاده")[size]
    val allTags: Set<Tag> get() = if (petSafe) tags + Tag.PET_SAFE else tags
    fun matches(q: String): Boolean {
        val t = PlantDb.norm(q)
        return t.isBlank() || PlantDb.norm("$fa $aka $sci $family").contains(t)
    }
}

